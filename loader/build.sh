#!/usr/bin/env bash
# build.sh — build claude-dispatch: a custom glibc ld.so that loads Claude Code,
# fixing the WSL1 launch + grep/find/rg breakage (anthropics/claude-code#38788).
#
# Pipeline: extract vendored glibc → apply rtld-dispatch.patch → cargo-build the
# no_std dispatch staticlib → stage it into the glibc build → configure + make
# → strip the conda-gcc auto-RPATH (ld.so asserts on it) → emit elf/ld.so as the
# claude-dispatch binary. The kernel execs it, so /proc/self/exe is genuinely
# claude-dispatch; its dl_main hook selects CLAUDE_BIN as the program.
#
# Env knobs:
#   CLAUDE_BIN        path baked in as the default program (also a runtime override)
#   GLIBC_TARBALL     glibc source tarball (default: loader/glibc/glibc-*.tar.xz)
#   JOBS              parallelism (default: nproc)
#   BUILDDIR          scratch build dir (default: loader/.build)
set -euo pipefail

here="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
CLAUDE_BIN="${CLAUDE_BIN:-$HOME/.local/bin/claude}"
GLIBC_TARBALL="${GLIBC_TARBALL:-$(echo "$here"/glibc/glibc-*.tar.xz)}"
JOBS="${JOBS:-$(nproc)}"
BUILDDIR="${BUILDDIR:-$here/.build}"
SRC="$BUILDDIR/glibc-src"
OBJ="$BUILDDIR/glibc-obj"

command -v cargo >/dev/null  || { echo "error: cargo not found (pixi add rust)"  >&2; exit 1; }
command -v gcc   >/dev/null  || { echo "error: gcc not found (pixi add gcc)"     >&2; exit 1; }
command -v patchelf >/dev/null || { echo "error: patchelf not found (pixi add patchelf)" >&2; exit 1; }
[ -f "$GLIBC_TARBALL" ] || { echo "error: glibc tarball not found: $GLIBC_TARBALL (git lfs pull?)" >&2; exit 1; }

echo "==> claude binary : $CLAUDE_BIN"
echo "==> glibc tarball : $GLIBC_TARBALL"
echo "==> build dir     : $BUILDDIR"

# 1. fresh source + our patch
rm -rf "$SRC" "$OBJ"; mkdir -p "$SRC" "$OBJ"
echo "==> extracting glibc"
tar xf "$GLIBC_TARBALL" -C "$SRC" --strip-components=1
echo "==> applying rtld-dispatch.patch"
( cd "$SRC" && patch -p1 < "$here/rtld-dispatch.patch" )

# 2. the no_std dispatch staticlib (CLAUDE_BIN baked in as the compile-time default)
echo "==> building dispatch staticlib (CLAUDE_BIN=$CLAUDE_BIN)"
printf '// generated by build.sh — the compile-time default program path\npub const DEFAULT_CLAUDE_BIN: &[u8] = b"%s\\0";\n' "$CLAUDE_BIN" > "$here/src/default_bin.rs"
( cd "$here" && cargo build --release )
cp "$here/target/release/libclaude_dispatch.a" "$OBJ-claude_dispatch.a"

# 3. configure. Use the conda toolchain's own sysroot kernel headers (do NOT
#    force --with-headers — it breaks the version check under conda gcc).
#    multi-arch is default-on for x86_64 here. This matches the proven build.
echo "==> configuring glibc"
( cd "$OBJ" && CFLAGS="-g -O2" "$SRC/configure" \
    --prefix=/usr \
    --disable-werror --disable-profile > configure.log 2>&1 )

# 4. stage our object where the patched elf/Makefile expects it, then build
mkdir -p "$OBJ/elf"
cp "$OBJ-claude_dispatch.a" "$OBJ/elf/claude_dispatch.a"
echo "==> building glibc (this takes a while; log: $OBJ/make.log)"
( cd "$OBJ" && make -j"$JOBS" > make.log 2>&1 )

# 5. strip the conda-gcc auto-injected RPATH (ld.so asserts: DT_RPATH must be NULL)
echo "==> stripping RPATH from ld.so"
patchelf --remove-rpath "$OBJ/elf/ld.so"

echo
echo "✓ built: $OBJ/elf/ld.so   (the claude-dispatch binary)"
echo "  self-test:"
"$OBJ/elf/ld.so" /bin/echo "  claude-dispatch ld.so runs OK" || echo "  WARNING: self-test failed"
