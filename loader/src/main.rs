//! claude-dispatch — program selector linked into a custom ld.so (the mid-land design).
//!
//! Called from a tiny hook in glibc's `dl_main` (right after `_dl_rtld_map.l_name`
//! is set, in the run-as-program path). The kernel execs our ld.so directly, so
//! `/proc/self/exe` — hence CLAUDE_CODE_EXECPATH — genuinely is claude-dispatch.
//!
//! We do NOT touch the initial stack: we set `_dl_argv[0]` (== `rtld_progname`,
//! the file ld.so loads) to CLAUDE_BIN, and report the bundled-tool argv0 to
//! restore post-load. `_dl_argv` is not advanced, so glibc's `skip_args` stays 0
//! and `_dl_start_args_adjust` is a no-op — the program receives the kernel argv
//! unchanged: `[ugrep|claude-dispatch, user args…]`, which is exactly what claude
//! wants (it dispatches its bundled ugrep/rg/bfs off argv[0] itself).
//!
//! `no_std`, no malloc; resolves only memcpy/memset/memcmp against rtld.
#![no_std]
#![no_main]

use core::ffi::{c_char, c_int};

#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! {
    loop {}
}

/// Satisfies the C-ABI `rust_eh_personality` reference under `-z defs` (panic=abort).
#[no_mangle]
pub extern "C" fn rust_eh_personality() {}

const TOOLS: [&[u8]; 3] = [b"ugrep", b"rg", b"bfs"];

/// Compile-time default program path (NUL-terminated), generated by build.rs into
/// OUT_DIR from $CLAUDE_BIN. The runtime `CLAUDE_BIN=` env override takes precedence.
include!(concat!(env!("OUT_DIR"), "/default_bin.rs"));

/// dl_main hook. `argv` = `_dl_argv`, `environ` = `__environ`, `argv0_out` = `&argv0`.
/// Returns 1 if we selected the program (caller skips ld.so's option parsing), else 0.
#[no_mangle]
pub unsafe extern "C" fn claude_dispatch(
    argv: *mut *const c_char,
    environ: *const *const c_char,
    argv0_out: *mut *const c_char,
) -> c_int {
    if argv.is_null() {
        return 0;
    }
    let orig0 = *argv; // how we were invoked: "ugrep", "…/claude-dispatch", …

    // The file ld.so should load: CLAUDE_BIN env override → compile-time default.
    let claude = match env_lookup(environ, b"CLAUDE_BIN") {
        Some(p) if *p != 0 => p,
        _ => DEFAULT_CLAUDE_BIN.as_ptr() as *const c_char,
    };

    // Bundled tool? (basename of argv[0]) → present that as the program's argv[0].
    if !orig0.is_null() {
        let b = basename(orig0);
        for t in TOOLS {
            if cstr_eq(b, t) {
                *argv0_out = orig0; // restored at dl_main's `if (argv0) _dl_argv[0]=argv0`
                break;
            }
        }
    }

    *argv = claude; // _dl_argv[0] = rtld_progname = CLAUDE_BIN (the load target)
    1
}

unsafe fn env_lookup(environ: *const *const c_char, key: &[u8]) -> Option<*const c_char> {
    if environ.is_null() {
        return None;
    }
    let mut p = environ;
    while !(*p).is_null() {
        let s = *p;
        let mut i = 0;
        let hit = loop {
            if i == key.len() {
                break *s.add(i) as u8 == b'=';
            }
            if *s.add(i) as u8 != key[i] {
                break false;
            }
            i += 1;
        };
        if hit {
            return Some(s.add(key.len() + 1));
        }
        p = p.add(1);
    }
    None
}

unsafe fn basename(p: *const c_char) -> *const c_char {
    let mut last = p;
    let mut q = p;
    while *q != 0 {
        if *q == b'/' as c_char {
            last = q.add(1);
        }
        q = q.add(1);
    }
    last
}

unsafe fn cstr_eq(p: *const c_char, want: &[u8]) -> bool {
    let mut i = 0;
    loop {
        let c = *p.add(i) as u8;
        if i == want.len() {
            return c == 0;
        }
        if c != want[i] {
            return false;
        }
        i += 1;
    }
}
