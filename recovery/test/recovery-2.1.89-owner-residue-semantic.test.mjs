function sha256(value) {
  return crypto.createHash('sha256').update(value).digest('hex')
}

function increment(map, key) {
  map.set(key, (map.get(key) ?? 0) + 1)
}

function collectSignature(source, controls, operators) {
  const ast = parse(source, {
    allowHashBang: true,
    allowReturnOutsideFunction: true,
    ecmaVersion: 'latest',
    sourceType: 'module',
  })
  const visit = node => {
    if (!node || typeof node !== 'object') return
    if (Array.isArray(node)) {
      for (const child of node) visit(child)
      return
    }
    if (
      /^(?:If|Switch|For|While|DoWhile|Try|Catch|Conditional|Logical|Await|Yield|Return|Throw)/.test(
        node.type,
      )
    ) {
      increment(controls, node.type)
    }
    if (typeof node.operator === 'string') increment(operators, node.operator)
    for (const [key, child] of Object.entries(node)) {
      if (!['end', 'loc', 'raw', 'start'].includes(key)) visit(child)
    }
  }
  visit(ast)
}

